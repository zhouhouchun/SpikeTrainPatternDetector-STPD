import STPDCore
import SwiftUI

/// Standalone view for the distribution-first foundation (D1-D3). It renders a pre-shaped
/// `ISIDistributionFoundationPresentation` (from STPDCore) and depends ONLY on STPDCore + SwiftUI —
/// deliberately NO `RasterDocument` / `WorkbenchSection` dependency, so it compiles and previews
/// without the (currently dirty) Workbench nav files. Navigation wiring is a separate later step.
///
/// This is the distribution-first counterpart to the old QC `DatasetISIHistogramView`, and is clearly
/// labelled as such.
struct ISIDistributionFoundationView: View {
    let presentation: ISIDistributionFoundationPresentation

    /// Trains selected for the stacked composition (UI-2C). Held as local `@State` so the control is
    /// self-contained — deliberately NOT wired to Workbench selection yet. Stale ids are harmless:
    /// `selectedDetails` filters against the current presentation.
    @State private var selectedTrainIDs: Set<String> = []

    /// How many trains the "Top N" quick action selects (by valid-ISI count).
    private let topN = 5

    /// The selected trains in stable `perTrainDetails` order (stacking order + color index), with stale
    /// ids dropped so the control stays consistent after a dataset swap.
    private var selectedDetails: [ISIDistributionTrainDetail] {
        presentation.selectedTrainDetails(selectedTrainIDs)
    }

    /// Selected trains paired with their stable colors, in stacking order — what the chart draws.
    private var stackedTrains: [(detail: ISIDistributionTrainDetail, color: Color)] {
        selectedDetails.map { ($0, trainColor($0.trainID)) }
    }

    /// The train whose detailed priors are drawn on the chart (UI-2D). Requested via `focusedTrainID`,
    /// but always constrained to the selected set (defaults to the first selected train, and falls back
    /// there when its train is deselected). `nil` when nothing is selected.
    @State private var focusedTrainID: String?

    private var focusedDetail: ISIDistributionTrainDetail? {
        presentation.focusedTrainDetail(requested: focusedTrainID, within: selectedTrainIDs)
    }

    /// Focus-picker binding reflecting the EFFECTIVE focus, so the control always shows the train whose
    /// priors are on the chart (even when the request defaulted/fell back).
    private var focusSelection: Binding<String?> {
        Binding(get: { focusedDetail?.trainID }, set: { focusedTrainID = $0 })
    }

    /// TSW-2 candidates (debug-only, unwired) for a given train.
    private func tswCandidates(for trainID: String) -> [TSWCandidateRow] {
        presentation.tswCandidatesByTrainID[trainID] ?? []
    }

    /// TSW candidates for the focused train — the only ones overlaid on the chart (to avoid clutter).
    private var focusedTSWCandidates: [TSWCandidateRow] {
        focusedDetail.map { tswCandidates(for: $0.trainID) } ?? []
    }

    /// Curated per-train palette, deliberately avoiding the family band hues (burst=orange, tonic=green,
    /// pause=blue) so train stacks read distinctly against the bands. Used for the first N trains.
    private static let trainPalette: [Color] = [.pink, .purple, .brown, .indigo, .red, .yellow, .teal, .mint, .cyan]

    /// Stable color for a train, keyed by its index in `perTrainDetails` — so a train keeps its color
    /// regardless of which others are selected. The curated palette covers the common case; beyond it,
    /// colors are generated by golden-angle hue spacing so 10+ trains still get DISTINCT (if less
    /// curated) colors rather than wrapping back onto `palette[0…]` and colliding.
    private func trainColor(_ trainID: String) -> Color {
        guard let idx = presentation.perTrainDetails.firstIndex(where: { $0.trainID == trainID }) else { return .gray }
        if idx < Self.trainPalette.count { return Self.trainPalette[idx] }
        let overflow = idx - Self.trainPalette.count
        let hue = (0.618_033_988_75 * Double(overflow + 1)).truncatingRemainder(dividingBy: 1.0)
        return Color(hue: hue,
                     saturation: overflow.isMultiple(of: 2) ? 0.85 : 0.60,
                     brightness: overflow.isMultiple(of: 2) ? 0.80 : 0.98)
    }

    /// Convenience for the eventual nav call site (and the preview): shape the presentation from a
    /// dataset, preferring a D2-wired run distribution when available.
    init(dataset: SpikeDataset, runDistribution: DatasetISIDistribution?, minimumValidISISec: Double) {
        self.init(presentation: .from(dataset: dataset, runDistribution: runDistribution, minimumValidISISec: minimumValidISISec))
    }

    init(presentation: ISIDistributionFoundationPresentation) {
        self.presentation = presentation
    }

    var body: some View {
        ScrollView {
            VStack(alignment: .leading, spacing: 20) {
                header
                if presentation.pooledValidISICount == 0 && presentation.perTrain.isEmpty {
                    emptyState
                } else {
                    selectedTrainControl
                    chartSection
                    selectedTrainPriorsSection
                    tswCandidatesSection
                    quantileSection
                    perTrainSection
                    intervalSection
                }
            }
            .padding(20)
            .frame(maxWidth: .infinity, alignment: .topLeading)
        }
    }

    // MARK: Header

    private var header: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(alignment: .firstTextBaseline, spacing: 10) {
                Text("分布优先基础（D1-D3）")
                    .font(.title3.weight(.semibold))
                badge(sourceText, tint: presentation.source == .detectionRun ? .green : .orange)
                Spacer()
            }
            Text("分布优先 ISI 模型（D1/D2）与 D3 派生的 burst/tonic/pause 区间先验——独立于旧的 QC ISI 直方图。")
                .font(.callout)
                .foregroundStyle(.secondary)
            HStack(spacing: 14) {
                metric("Dataset", presentation.datasetName)
                metric("Floor", "\(ms(presentation.floorSec)) ms")
                metric("Contributing trains", "\(presentation.contributingTrainCount)")
                metric("Pooled valid ISIs", "\(presentation.pooledValidISICount)")
            }
            .font(.caption)
        }
    }

    private var sourceText: String {
        switch presentation.source {
        case .detectionRun: return "from detection run"
        case .computedFromDataset: return "computed from dataset"
        }
    }

    // MARK: Sections

    private var quantileSection: some View {
        sectionCard("Dataset quantiles (seconds → ms)") {
            Grid(alignment: .leading, horizontalSpacing: 14, verticalSpacing: 6) {
                quantileHeaderRow
                Divider().gridCellColumns(9)
                quantileRow(presentation.pooled)
                if let balanced = presentation.trainBalanced {
                    quantileRow(balanced)
                }
            }
        }
    }

    private var perTrainSection: some View {
        sectionCard("Per-train valid ISIs + key quantiles") {
            Grid(alignment: .leading, horizontalSpacing: 14, verticalSpacing: 6) {
                quantileHeaderRow
                Divider().gridCellColumns(9)
                ForEach(presentation.perTrain, id: \.trainID) { row in
                    quantileRow(row)
                }
            }
        }
    }

    private var intervalSection: some View {
        sectionCard("D3 dataset interval priors") {
            if presentation.datasetIntervals.isEmpty {
                Text("尚未派生数据集范围的 burst/tonic/pause 先验。")
                    .foregroundStyle(.secondary)
            } else {
                VStack(alignment: .leading, spacing: 10) {
                    Text("core = 中心身份范围（如 tonic q25–q75）；acc = 更宽的接受/成员范围；bridge = burst 延伸范围。")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    ForEach(presentation.datasetIntervals, id: \.self) { interval in
                        intervalRow(interval)
                    }
                }
            }
        }
    }

    // MARK: Rows

    private var quantileHeaderRow: some View {
        GridRow {
            cell("Scope", bold: true)
            cell("n", bold: true)
            cell("min", bold: true); cell("q10", bold: true); cell("q25", bold: true)
            cell("q50", bold: true); cell("q75", bold: true); cell("q90", bold: true); cell("max", bold: true)
        }
    }

    private func quantileRow(_ row: ISIDistributionQuantileRow) -> some View {
        GridRow {
            cell(row.label)
            cell("\(row.validISICount)")
            cell(ms(row.minSec)); cell(ms(row.q10Sec)); cell(ms(row.q25Sec))
            cell(ms(row.q50Sec)); cell(ms(row.q75Sec)); cell(ms(row.q90Sec)); cell(ms(row.maxSec))
        }
    }

    private func intervalRow(_ interval: ISIModeIntervalRow) -> some View {
        HStack(alignment: .firstTextBaseline, spacing: 10) {
            Text(familyName(interval.family))
                .font(.body.weight(.semibold))
                .foregroundStyle(familyColor(interval.family))
                .frame(width: 64, alignment: .leading)

            VStack(alignment: .leading, spacing: 2) {
                // Core (identity) interval.
                Text("核心  [\(ms(interval.lowerSec)) – \(ms(interval.upperSec)) ms]")
                    .monospacedDigit()
                // Acceptance (wider membership) interval, shown only when it differs from the core.
                if interval.acceptanceLowerSec != nil || interval.acceptanceUpperSec != nil {
                    Text("接受范围  [\(ms(interval.acceptanceLowerSec ?? interval.lowerSec)) – \(ms(interval.acceptanceUpperSec ?? interval.upperSec)) ms]")
                        .monospacedDigit()
                        .foregroundStyle(.secondary)
                }
                // Burst bridge/extension upper.
                if let bridge = interval.bridgeUpperSec {
                    Text("桥接 → \(ms(bridge)) ms")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                }
            }

            Spacer(minLength: 8)

            badge(interval.scope.rawValue, tint: .indigo)
            badge(interval.provenanceOrigin.rawValue, tint: .purple)
            if interval.mayPropagateToDataset { badge("propagate", tint: .green) }
            if !interval.maySelectFinalLabel { badge("no-select", tint: .gray) }
            if interval.isAuditOnly { badge("audit-only", tint: .gray) }
            if !interval.isValid { badge("invalid", tint: .red) }
        }
    }

    // MARK: Selected-train composition (UI-2C)

    private var selectedTrainControl: some View {
        VStack(alignment: .leading, spacing: 8) {
            HStack(spacing: 10) {
                Text("叠加序列（堆叠）")
                    .font(.callout.weight(.medium))
                Text("\(selectedDetails.count) of \(presentation.perTrainDetails.count) selected")
                    .font(.caption).foregroundStyle(.secondary)
                Spacer()
                Button("全不选") { selectedTrainIDs = [] }
                    .disabled(selectedTrainIDs.isEmpty)
                Button("全选") { selectedTrainIDs = Set(presentation.perTrainDetails.map(\.trainID)) }
                    .disabled(selectedDetails.count == presentation.perTrainDetails.count)
                Button("前 \(min(topN, presentation.perTrainDetails.count)) 条") { selectTopByISICount(topN) }
                    .disabled(presentation.perTrainDetails.count <= topN)
            }
            .buttonStyle(.bordered)
            .controlSize(.small)

            LazyVGrid(columns: [GridItem(.adaptive(minimum: 180), spacing: 8)], alignment: .leading, spacing: 8) {
                ForEach(presentation.perTrainDetails, id: \.trainID) { detail in
                    trainToggleChip(detail)
                }
            }

            if selectedDetails.count > 1 {
                focusControl
            }
        }
    }

    /// UI-2D focus picker: choose ONE of the selected trains whose detailed priors are drawn on the
    /// chart (the stacked bars still show every selected train's composition). Only shown when more than
    /// one train is selected — with a single selection that train is already the focus.
    private var focusControl: some View {
        HStack(spacing: 8) {
            Text("聚焦")
                .font(.callout.weight(.medium))
            Picker("聚焦序列", selection: focusSelection) {
                ForEach(selectedDetails, id: \.trainID) { detail in
                    Text(detail.trainName).tag(String?.some(detail.trainID))
                }
            }
            .labelsHidden()
            .frame(maxWidth: 260)
            if let focus = focusedDetail {
                HStack(spacing: 5) {
                    RoundedRectangle(cornerRadius: 2).fill(trainColor(focus.trainID)).frame(width: 12, height: 10)
                    Text("图中绘制的先验：\(focus.trainName)")
                        .font(.caption).foregroundStyle(.secondary)
                }
            }
            Spacer()
        }
    }

    private func selectTopByISICount(_ n: Int) {
        let top = presentation.perTrainDetails
            .sorted { $0.validISICount > $1.validISICount }
            .prefix(n)
            .map(\.trainID)
        selectedTrainIDs = Set(top)
    }

    private func trainToggleChip(_ detail: ISIDistributionTrainDetail) -> some View {
        let isOn = selectedTrainIDs.contains(detail.trainID)
        let color = trainColor(detail.trainID)
        return Button {
            if isOn { selectedTrainIDs.remove(detail.trainID) } else { selectedTrainIDs.insert(detail.trainID) }
        } label: {
            HStack(spacing: 6) {
                RoundedRectangle(cornerRadius: 2)
                    .fill(isOn ? color : Color.secondary.opacity(0.35))
                    .frame(width: 12, height: 12)
                Text(detail.trainName).lineLimit(1)
                Spacer(minLength: 4)
                Text("\(detail.validISICount)").font(.caption2).foregroundStyle(.secondary).monospacedDigit()
            }
            .padding(.horizontal, 8).padding(.vertical, 5)
            .frame(maxWidth: .infinity, alignment: .leading)
            .background(isOn ? color.opacity(0.14) : Color.secondary.opacity(0.06),
                        in: RoundedRectangle(cornerRadius: 6))
            .overlay(
                RoundedRectangle(cornerRadius: 6)
                    .stroke(isOn ? color.opacity(0.55) : Color.secondary.opacity(0.18), lineWidth: 1))
        }
        .buttonStyle(.plain)
    }

    // Priors option chosen: a COMPACT LIST of ALL selected trains' priors, each group prefixed with the
    // train's stack color. Simpler than a separate "focused train" control (no extra state), and the
    // color header maps each prior group directly to its stacked segment; the ScrollView absorbs length.
    private var selectedTrainPriorsSection: some View {
        sectionCard("Selected-train interval priors") {
            if selectedDetails.isEmpty {
                Text("请在上方选择一条或多条序列，以堆叠其贡献并列出各序列的局部先验。")
                    .foregroundStyle(.secondary)
            } else {
                VStack(alignment: .leading, spacing: 14) {
                    Text("每条所选序列的局部先验——“trainLocal”徽标用于区别下方的数据集先验。（当前显示全部所选序列；取消选择可缩短列表。）")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    ForEach(selectedDetails, id: \.trainID) { detail in
                        VStack(alignment: .leading, spacing: 6) {
                            HStack(spacing: 6) {
                                RoundedRectangle(cornerRadius: 2).fill(trainColor(detail.trainID)).frame(width: 12, height: 12)
                                Text(detail.trainName).font(.subheadline.weight(.semibold))
                                Text("(\(detail.validISICount) valid ISIs)").font(.caption).foregroundStyle(.secondary)
                                if detail.trainID == focusedDetail?.trainID {
                                    badge("focus", tint: .accentColor)   // priors drawn on the chart
                                }
                            }
                            if detail.intervals.isEmpty {
                                Text("尚未派生序列局部的 burst/tonic/pause 先验。")
                                    .font(.caption).foregroundStyle(.secondary)
                            } else {
                                ForEach(detail.intervals, id: \.self) { interval in
                                    intervalRow(interval)
                                }
                            }
                        }
                    }
                }
            }
        }
    }

    // MARK: TSW-2 tonic structural candidates (debug-only; unwired)

    private var tswCandidatesSection: some View {
        sectionCard("TSW tonic structural candidates") {
            if selectedDetails.isEmpty {
                Text("请在上方选择一条或多条序列，以列出其 TSW-2 序列局部 tonic 结构候选（仅用于调试；TSW 不影响检测结果）。")
                    .foregroundStyle(.secondary)
            } else {
                VStack(alignment: .leading, spacing: 12) {
                    Text("TSW-2 根据每条序列的 ISI 顺序发现序列局部 tonic 窗口；它不同于下方 D3 分布范围：D3 表示 ISI 数值先验，TSW 表示有序连续结构。图中，聚焦序列的候选以紫色 ISI 数值范围（最小–最大）显示，而不是时间跨度；序列跨度由此处的 ISI 索引范围表示。")
                        .font(.caption)
                        .foregroundStyle(.secondary)
                    ForEach(selectedDetails, id: \.trainID) { detail in
                        let rows = tswCandidates(for: detail.trainID)
                        let isFocus = detail.trainID == focusedDetail?.trainID
                        VStack(alignment: .leading, spacing: 6) {
                            HStack(spacing: 6) {
                                RoundedRectangle(cornerRadius: 2).fill(trainColor(detail.trainID)).frame(width: 12, height: 12)
                                Text(detail.trainName).font(.subheadline.weight(.semibold))
                                if isFocus { badge("focus", tint: .accentColor) }
                                Text("\(rows.count) candidate\(rows.count == 1 ? "" : "s")")
                                    .font(.caption).foregroundStyle(.secondary)
                            }
                            .padding(isFocus ? 4 : 0)
                            .background(isFocus ? Color.purple.opacity(0.08) : Color.clear,
                                        in: RoundedRectangle(cornerRadius: 5))
                            if rows.isEmpty {
                                Text("没有 TSW tonic 结构候选。")
                                    .font(.caption).foregroundStyle(.secondary)
                            } else {
                                ForEach(rows, id: \.self) { row in tswRow(row) }
                            }
                        }
                    }
                }
            }
        }
    }

    private func tswRow(_ row: TSWCandidateRow) -> some View {
        VStack(alignment: .leading, spacing: 2) {
            HStack(spacing: 8) {
                Text("ISI 序列 [\(row.startISIIndex)–\(row.endISIIndex)] · spikes [\(row.startSpikeIndex)–\(row.endSpikeIndex)] · \(row.isiCount) 个 ISI")
                    .font(.caption).monospacedDigit()
                badge(tswRouteLabel(row.route), tint: tswRouteTint(row.route))
                badge(row.source, tint: row.isRefined ? .indigo : .purple)
                badge(modeReliabilityLabel(row.modeReliability), tint: modeReliabilityTint(row.modeReliability))
                if row.outsideD3Acceptance { badge("outside D3 acceptance", tint: .orange) }
                if row.reviewRequired { badge("review", tint: .yellow) }
            }
            // TSW-3 refinement provenance: original → refined span + shrink/bridge badges.
            if row.isRefined {
                HStack(spacing: 8) {
                    if let os = row.originalStartISIIndex, let oe = row.originalEndISIIndex {
                        Text("由 [\(os)–\(oe)] 精炼").font(.caption2).foregroundStyle(.indigo).monospacedDigit()
                    }
                    if row.lowSideTrimmed > 0 { badge("−\(row.lowSideTrimmed) low", tint: .teal) }
                    if row.highSideTrimmed > 0 { badge("−\(row.highSideTrimmed) high", tint: .teal) }
                    if row.bridgeCount > 0 { badge("bridge ×\(row.bridgeCount)\(row.bridgeSide.map { " (\($0))" } ?? "")", tint: .blue) }
                    if row.usedReliableBurstBoundary { badge("D3 valley", tint: .green) }
                }
            }
            HStack(spacing: 8) {
                Text("数值范围 \(ms(row.lowerSec))–\(ms(row.upperSec)) ms")
                    .font(.caption2).foregroundStyle(.purple).monospacedDigit()
                Text("CV \(num(row.cv)) · CV2 \(num(row.cv2)) · LV \(num(row.lv))")
                    .font(.caption2).foregroundStyle(.secondary).monospacedDigit()
                if let reason = row.boundaryReason {
                    Text("边界：\(reason)").font(.caption2).foregroundStyle(.secondary)
                }
            }
        }
    }

    /// Short label + color for the D3-HF fast/tonic mode-separation reliability of the candidate's train.
    /// `.unavailable` ("fast ?") means the separation was not characterized — distinct from a computed
    /// `.noFastMode` ("no fast").
    private func modeReliabilityLabel(_ reliability: String) -> String {
        switch reliability {
        case "reliable": return "fast✓sep"
        case "degenerate": return "fast~sep"
        case "notSeparable": return "fast✗sep"
        case "noFastMode": return "no fast"
        case "unavailable": return "fast ?"
        default: return reliability
        }
    }
    private func modeReliabilityTint(_ reliability: String) -> Color {
        switch reliability {
        case "reliable": return .green
        case "degenerate": return .yellow
        case "notSeparable": return .orange
        case "noFastMode": return .gray
        case "unavailable": return .gray
        default: return .gray
        }
    }

    /// Short label + color for a TSW-2A family route (classic = green; HF = amber; review = orange;
    /// too-fast = gray). Debug-only; TSW is unwired.
    private func tswRouteLabel(_ route: String) -> String {
        switch route {
        case "classicTonic": return "classic tonic"
        case "highFrequencyTonic": return "HF tonic"
        case "highFrequencySpiking": return "HF spiking"
        case "possibleTonicReview": return "tonic? review"
        case "tooFastForClassicTonic": return "too fast"
        default: return route
        }
    }
    private func tswRouteTint(_ route: String) -> Color {
        switch route {
        case "classicTonic": return .green
        case "highFrequencyTonic", "highFrequencySpiking": return .orange
        case "possibleTonicReview": return .yellow
        case "tooFastForClassicTonic": return .gray
        default: return .gray
        }
    }

